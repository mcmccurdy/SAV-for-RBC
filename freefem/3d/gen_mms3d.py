"""Write mms3d.idp: 3D manufactured solution for nsb3d.edp on [0,2pi) x [-1,1] x [0,2pi), walls y = s = -1, +1.
u = (d_y psi, -d_x psi - d_z chi, d_y chi), psi = sin t sin x (1-y^2), chi = 1/2 sin t sin z (1-y^2): div u = 0, u_y = 0 on walls."""
import sympy as sp
x, y, z, t, s = sp.symbols('x y z t s', real=True)
nu, kap, G, Tr, l = sp.symbols('nu kap G Tref l', real=True)
psi = sp.sin(t)*sp.sin(x)*(1 - y**2); chi = sp.sin(t)*sp.sin(z)*(1 - y**2)/2
ux, uy, uz = sp.diff(psi, y), -sp.diff(psi, x) - sp.diff(chi, z), sp.diff(chi, y)
assert sp.simplify(sp.diff(ux, x) + sp.diff(uy, y) + sp.diff(uz, z)) == 0
assert sp.simplify(uy.subs(y, 1)) == 0 and sp.simplify(uy.subs(y, -1)) == 0
p = sp.sin(t)*sp.cos(x)*sp.sin(y)*sp.cos(z)
T = (1 - y)/2 + sp.cos(t)*(1 - y**2)*(sp.sin(x) + y*sp.cos(x)/2 + sp.cos(z)/2)/2
lap = lambda q: sp.diff(q, x, 2) + sp.diff(q, y, 2) + sp.diff(q, z, 2)
adv = lambda q: ux*sp.diff(q, x) + uy*sp.diff(q, y) + uz*sp.diff(q, z)
Sux = sp.diff(ux, t) + adv(ux) - nu*lap(ux) + sp.diff(p, x)
Suy = sp.diff(uy, t) + adv(uy) - nu*lap(uy) + sp.diff(p, y) - G*(T - Tr)
Suz = sp.diff(uz, t) + adv(uz) - nu*lap(uz) + sp.diff(p, z)
ST = sp.diff(T, t) + adv(T) - kap*lap(T)
Swx = (l*ux + nu*s*sp.diff(ux, y)).subs(y, s); Swz = (l*uz + nu*s*sp.diff(uz, y)).subs(y, s)
tm = sp.Symbol('tm'); ff = lambda e: sp.ccode(sp.simplify(e).subs(t, tm)).replace('M_PI', 'pi')
L = ['// AUTO-GENERATED by gen_mms3d.py: 3D manufactured solution for nsb3d.edp']
for n, e in [('mmsux', ux), ('mmsuy', uy), ('mmsuz', uz), ('mmsp', p), ('mmsT', T), ('mmsSux', Sux), ('mmsSuy', Suy), ('mmsSuz', Suz), ('mmsST', ST)]:
    L.append(f'macro {n}(tm) ({ff(e)}) //')
for n, e in [('mmsSwxbot', Swx.subs(s, -1)), ('mmsSwxtop', Swx.subs(s, 1)), ('mmsSwzbot', Swz.subs(s, -1)), ('mmsSwztop', Swz.subs(s, 1))]:
    L.append(f'macro {n}(tm) ({ff(e)}) //')
open('mms3d.idp', 'w').write('\n'.join(L) + '\n'); print(len(L) - 1, 'macros')
