"""Write mms.idp: exact solution and forcing of the manufactured solution of paper Section 6.1
for nsb.edp (same solution as tools/gen_mms.py). Walls y = s = -1, +1; x in [0, 2pi)."""
import sympy as sp
x, y, t, s = sp.symbols('x y t s', real=True)
nu, kap, G, Tr, l = sp.symbols('nu kap G Tref l', real=True)
psi = sp.sin(t)*sp.sin(x)*(1 - y**2)
ux, uy = sp.diff(psi, y), -sp.diff(psi, x)
p = sp.sin(t)*sp.cos(x)*sp.sin(y)
T = (1 - y)/2 + sp.cos(t)*(1 - y**2)*(sp.sin(x) + y*sp.cos(x)/2)/2
lap = lambda q: sp.diff(q, x, 2) + sp.diff(q, y, 2)
Sux = sp.diff(ux, t) + ux*sp.diff(ux, x) + uy*sp.diff(ux, y) - nu*lap(ux) + sp.diff(p, x)
Suy = sp.diff(uy, t) + ux*sp.diff(uy, x) + uy*sp.diff(uy, y) - nu*lap(uy) + sp.diff(p, y) - G*(T - Tr)
ST = sp.diff(T, t) + ux*sp.diff(T, x) + uy*sp.diff(T, y) - kap*lap(T)
Sw = sp.expand((l*ux + nu*s*sp.diff(ux, y)).subs(y, s))      # slip-condition forcing on the wall y = s
tt = sp.Symbol('tm')
def ff(e):
    return sp.ccode(sp.simplify(e).subs(t, tt))
lines = ['// AUTO-GENERATED by gen_mms_ff.py: manufactured solution of paper Section 6.1',
         '// tm = time; wall forcing Sw evaluated with s = -1 (y = -1) and s = +1 (y = +1)']
for name, e in [('mmsux', ux), ('mmsuy', uy), ('mmsp', p), ('mmsT', T), ('mmsSux', Sux), ('mmsSuy', Suy), ('mmsST', ST)]:
    lines.append(f'macro {name}(tm) ({ff(e)}) //')
for name, e in [('mmsuxdx', sp.diff(ux, x)), ('mmsuxdy', sp.diff(ux, y)), ('mmsuydx', sp.diff(uy, x)), ('mmsuydy', sp.diff(uy, y)),
                ('mmsTdx', sp.diff(T, x)), ('mmsTdy', sp.diff(T, y))]:
    lines.append(f'macro {name}(tm) ({ff(e)}) //')
lines.append(f'macro mmsSwbot(tm) ({ff(Sw.subs(s, -1))}) //')
lines.append(f'macro mmsSwtop(tm) ({ff(Sw.subs(s, 1))}) //')
open('mms.idp', 'w').write('\n'.join(lines) + '\n')
print('\n'.join(lines))
